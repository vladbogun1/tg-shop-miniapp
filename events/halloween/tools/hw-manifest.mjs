// Lists the redrawn Halloween pictures (site/public/mascot-hw, site/public/case-hw, frontend/public/case-hw)
// into shared/src/event-assets.ts, so the middlewares swap only the files that really have a Halloween
// version — a picture that was not redrawn keeps its usual one instead of a 404.
// Run from the repo root after adding or removing a picture: node events/halloween/tools/hw-manifest.mjs
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

function walk(dir) {
  let out = [];
  let names;
  try {
    names = readdirSync(dir);
  } catch {
    return out;
  }
  for (const n of names) {
    const p = join(dir, n);
    if (statSync(p).isDirectory()) out = out.concat(walk(p));
    else out.push(p);
  }
  return out;
}

const list = (dir, prefix) =>
  walk(dir)
    .map((p) => prefix + relative(dir, p).split(sep).join("/"))
    .sort();

const site = [...list("site/public/mascot-hw", "/mascot/"), ...list("site/public/case-hw", "/case/")];
const app = list("frontend/public/case-hw", "/case/");

const fmt = (a) => a.map((p) => `  "${p}",`).join("\n");
writeFileSync(
  "shared/src/event-assets.ts",
  `// Generated by events/halloween/tools/hw-manifest.mjs — do not edit. Halloween 2026, remove with the event.
/** Site paths (/mascot/…, /case/…) that have a redrawn copy under public/mascot-hw or public/case-hw. */
export const HW_SITE_ASSETS: ReadonlySet<string> = new Set([
${fmt(site)}
]);

/** Mini App paths (/case/…) that have a redrawn copy under frontend/public/case-hw. */
export const HW_APP_ASSETS: ReadonlySet<string> = new Set([
${fmt(app)}
]);
`
);
console.log(`site ${site.length}, app ${app.length}`);
