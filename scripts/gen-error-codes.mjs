#!/usr/bin/env node
/**
 * Коды клиентских ошибок бэкенда -> packages/core/src/api/error-codes.d.ts (только тип, ноль рантайма).
 * Источник — backend/src/test/resources/openapi/error-codes.json, его пишет OpenApiSnapshotTest из enum'ов
 * `<Модуль>Error` (поле `code` тела ошибки). Запускается из `npm run gen:api`.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = JSON.parse(fs.readFileSync(path.join(ROOT, "backend/src/test/resources/openapi/error-codes.json"), "utf8"));
const codes = [...src.codes].sort();
const out =
  "/**\n * This file was auto-generated by scripts/gen-error-codes.mjs from backend/src/test/resources/openapi/error-codes.json.\n" +
  " * Do not make direct changes to the file.\n */\n\n" +
  "/** Коды причин, которые бэкенд кладёт в поле `code` тела ошибки. */\n" +
  "export type ServerErrorCode =\n" +
  codes.map((c) => `  | "${c}"`).join("\n") +
  ";\n";
fs.writeFileSync(path.join(ROOT, "packages/core/src/api/error-codes.d.ts"), out);
console.log(`error-codes.d.ts: ${codes.length} кодов`);
