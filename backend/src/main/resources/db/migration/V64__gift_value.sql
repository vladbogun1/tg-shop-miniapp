-- ============================================================
--  Реестр подарков (docs/GIFT-CASE.md, «Реестр подарков и месячный лимит»).
--
--  order_items.gift_value_minor — обычная цена единицы подарка (копейки) на момент, когда
--  его положили в заказ: строка подарка идёт по цене 0, а для налогов подарок стоит по
--  обычной цене продажи. 0 у не-подарков.
--
--  Уже выданным подаркам цена берётся текущая цена товара — точнее восстановить нечем.
--
--  V64: V61/V62 заняты «Разом дешевше» (feat/bundles), V63 — потолок промокода.
--  Аддитивная: откат — только образами (старый бэкенд колонку не читает).
-- ============================================================
ALTER TABLE order_items
    ADD COLUMN gift_value_minor BIGINT NOT NULL DEFAULT 0 AFTER case_rarity;

UPDATE order_items i
  JOIN products p ON p.id = i.product_id
   SET i.gift_value_minor = p.price_minor
 WHERE i.gift = 1;
