--
--  Если из кейса выпал товар с размерами и в наличии их несколько, при оформлении бронируется
--  размер, которого больше всего на складе, а строка помечается variant_pending = 1:
--  покупатель выбирает свой размер из тех, что есть, в окне открытия кейса или в карточке
--  заказа (бронь переезжает на выбранный). Админка видит «размер не выбран».
-- ============================================================
ALTER TABLE order_items
    ADD COLUMN variant_pending TINYINT(1) NOT NULL DEFAULT 0 AFTER case_rarity;
