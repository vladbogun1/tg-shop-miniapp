-- ============================================================
--  Язык, который покупатель выбрал в приложении.
--
--  `language_code` рядом — это то, что сообщает Telegram, и его мы не трогаем:
--  оно перезаписывается при каждом входе. `locale` заполняется ТОЛЬКО когда
--  человек переключил язык руками, и поэтому главнее.
--
--  Нужно это боту: уведомления о заказе должны приходить на том же языке,
--  на котором человек видит магазин. Сообщения в канал продавца остаются
--  русскими независимо от этого поля.
-- ============================================================

ALTER TABLE users
    ADD COLUMN locale VARCHAR(5) NULL AFTER language_code;
