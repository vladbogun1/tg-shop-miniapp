#!/usr/bin/env bash
# Откат прода на прежний релиз — та же выкатка без даунтайма, только на старый тег.
#
#   infra/rollback.sh v3.42.0            # откатить на тег v3.42.0 (с дампом БД перед этим)
#   infra/rollback.sh v3.42.0 --no-backup
#
# Делает infra/deploy/deploy.sh <тег>: дамп (infra/backup.sh), git checkout тега (compose и конфиги
# совпадут с тем релизом), IMAGE_TAG в .env, pull и перекатка сервисов по одному без 502.
#
# Чего НЕ делает: не откатывает миграции базы. Если между релизами была миграция, несовместимая
# со старым образом (удалённые колонки/таблицы — например V48), бэкенд старого тега не стартует —
# deploy.sh это увидит (копия не станет готовой) и оставит прод на текущей версии; тогда откат только
# восстановлением дампа, снятого ПЕРЕД выкаткой (docs/DEPLOY-SERVER.md §5, «Восстановление»).
# У бэкендов до TELEGRAM_POLLING (≤ v3.49) временная копия тоже опрашивает бота: минуту в логах
# будут 409 Conflict, сообщения боту придут с задержкой — не страшно.
set -euo pipefail

to="${1:-}"
[ -n "$to" ] || { echo "usage: infra/rollback.sh <тег, например v3.42.0> [--no-backup]" >&2; exit 2; }
dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$dir"
from="$(grep -E '^IMAGE_TAG=' .env | tail -n1 | cut -d= -f2- | tr -d '\r')"

read -r -p "Откатить прод с ${from:-?} на $to? (yes/no) " a
[ "$a" = yes ] || { echo "отмена"; exit 1; }

# deploy.sh держит всё тело в main(), поэтому checkout старого тега (где этого файла может не быть)
# посреди выполнения ему не мешает.
exec bash "$dir/infra/deploy/deploy.sh" "$to" ${2:+"$2"}
